package curriculum.g;

public class Employee {
	String employeeId;
	String name;

	public void setEmployeeId(String id) {
		this.employeeId = id;
	}

	public String getEmployeeId() {
		return employeeId;
	}

	public void setName(String name) {
		this.name = name;
	}

	public String getName() {
		return name;
	}

}
